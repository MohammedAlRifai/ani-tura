const savedLanguage = (typeof window !== "undefined" && localStorage.getItem("hospital_eye_lang")) || "ar";

// Set initial document attributes
if (typeof document !== "undefined") {
  document.documentElement.lang = savedLanguage;
  document.documentElement.dir = savedLanguage === "ar" ? "rtl" : "ltr";
}

i18n.use(initReactI18next).init({
  resources,
  lng: savedLanguage,
  fallbackLng: "ar",
  interpolation: {
    escapeValue: false,
  },
});

export const toggleLanguage = () => {
  const newLang = i18n.language === "ar" ? "en" : "ar";
  i18n.changeLanguage(newLang);
  if (typeof window !== "undefined") {
    localStorage.setItem("hospital_eye_lang", newLang);
    document.documentElement.lang = newLang;
    document.documentElement.dir = newLang === "ar" ? "rtl" : "ltr";
  }
  return newLang;
};

export const setAppLanguage = (lang: "ar" | "en") => {
  i18n.changeLanguage(lang);
  if (typeof window !== "undefined") {
    localStorage.setItem("hospital_eye_lang", lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }
};

export default i18n;
